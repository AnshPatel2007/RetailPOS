import { test, expect } from '@playwright/test';
import { login, logout, TEST_USER } from './utils/auth-helper';

test('two stores receive partial shipments, resolve discrepancies and confirm physical returns with safe retries', async ({ page }, testInfo) => {
  test.setTimeout(60000);
  await login(page, TEST_USER.email); await page.goto('/inventory-transfers');
  const row = page.getByRole('row').filter({ hasText: 'TRF-FIXTURE' });
  const details = page.getByRole('dialog', { name: 'Transfer details', exact: true });
  await row.click(); await details.getByRole('button', { name: 'Ship', exact: true }).click();
  const shipped = page.waitForResponse(r => r.url().endsWith('/ship') && r.request().method() === 'POST');
  await page.getByRole('dialog').filter({ hasText: 'Ship transfer?' }).getByRole('button', { name: 'Ship', exact: true }).click();
  expect((await shipped).status()).toBe(200); await expect(details).toHaveCount(0);
  await row.click();
  await expect(details.getByRole('button', { name: 'Cancel', exact: true })).toHaveCount(0);
  await expect(details.getByRole('button', { name: 'Record returned goods', exact: true })).toHaveCount(0);
  await details.getByRole('button', { name: 'Request return', exact: true }).click();
  const returnRequest = page.getByRole('dialog', { name: 'Request a return', exact: true });
  await returnRequest.getByLabel('Reason / notes').fill('Please send two unopened units back');
  await returnRequest.getByRole('button', { name: 'Send return request', exact: true }).click();
  await expect(returnRequest).toHaveCount(0); await details.getByRole('button', { name: 'Close', exact: true }).click();
  await logout(page); await login(page, 'receiving@example.test'); await page.goto('/inventory-transfers');
  await row.click(); await expect(details.getByText('Please send two unopened units back')).toBeVisible();
  await details.getByRole('button', { name: 'Receive or resolve delivery', exact: true }).click();
  const receive = page.getByRole('dialog', { name: 'Receive transfer', exact: true });
  await receive.getByLabel('Fixture Transfer accepted').fill('4');
  await receive.getByRole('button', { name: 'Record quantities', exact: true }).click();
  await expect(receive.getByRole('alert')).toContainText('Choose a destination product');
  await receive.getByRole('button', { name: 'Use Fixture Received (FIXTURE-TRANSFER)', exact: true }).click();
  await expect(receive.getByRole('alert')).toHaveCount(0);
  await receive.evaluate(element => element.querySelector('.overflow-y-auto')?.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath('transfer-receive-desktop.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await receive.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await receive.getByRole('button', { name: 'Record quantities', exact: true }).scrollIntoViewIfNeeded();
  await expect(receive.getByRole('button', { name: 'Record quantities', exact: true })).toBeVisible();
  await receive.evaluate(element => element.querySelector('.overflow-y-auto')?.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath('transfer-receive-phone.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.route('**/api/inventory-transfers/*/receive', async route => { const response = await route.fetch(); expect(response.status()).toBe(200); await route.abort('failed'); }, { times: 1 });
  await receive.getByRole('button', { name: 'Record quantities', exact: true }).click();
  await expect(receive.getByRole('alert')).toContainText('uncertain');
  await page.reload(); await expect(details).toBeVisible(); await details.getByRole('button', { name: 'Receive or resolve delivery', exact: true }).click();
  await expect(receive.getByLabel('Fixture Transfer accepted')).toHaveValue('4');
  const replay = page.waitForResponse(r => r.url().endsWith('/receive') && r.request().method() === 'POST');
  await receive.getByRole('button', { name: 'Retry saved event', exact: true }).click();
  expect((await (await replay).json()).data.replayed).toBe(true);
  await expect(receive).toHaveCount(0); await expect(details.getByText('4 accepted at destination', { exact: true })).toBeVisible();
  await details.getByRole('button', { name: 'Receive or resolve delivery', exact: true }).click();
  await receive.getByLabel('Fixture Transfer accepted').fill('2');
  await receive.getByLabel('Fixture Transfer damaged').fill('1');
  await receive.getByLabel('Fixture Transfer missing').fill('1');
  await receive.getByLabel('Fixture Transfer send back').fill('2');
  await receive.getByLabel('Reason / notes').fill('One damaged, one confirmed lost, two dispatched back');
  await receive.getByRole('button', { name: 'Record quantities', exact: true }).click();
  await expect(receive).toHaveCount(0); await expect(details.getByText('2 returning to source', { exact: true })).toBeVisible();
  await details.getByRole('button', { name: 'Close', exact: true }).click();
  await logout(page); await login(page, TEST_USER.email); await page.goto('/inventory-transfers');
  await page.getByRole('button', { name: 'Toggle theme', exact: true }).filter({ visible: true }).click();
  await row.click(); await details.getByRole('button', { name: 'Record returned goods', exact: true }).click();
  const returned = page.getByRole('dialog', { name: 'Record returned goods', exact: true });
  await returned.getByLabel('Fixture Transfer accepted').fill('1');
  await returned.getByLabel('Fixture Transfer damaged').fill('1');
  await returned.getByLabel('Reason / notes').fill('One good unit physically returned; one damaged');
  await page.screenshot({ path: testInfo.outputPath('transfer-return-dark.png'), animations: 'disabled' });
  await page.route('**/api/inventory-transfers/*/receive-return', async route => { const response = await route.fetch(); expect(response.status()).toBe(200); await route.abort('failed'); }, { times: 1 });
  await returned.getByRole('button', { name: 'Record quantities', exact: true }).click();
  await expect(returned.getByRole('alert')).toContainText('uncertain');
  await page.reload(); await expect(details).toBeVisible(); await expect(details.getByText('Closed', { exact: true })).toBeVisible();
  await details.getByRole('button', { name: 'Record returned goods', exact: true }).click();
  await returned.getByRole('button', { name: 'Retry saved event', exact: true }).click();
  await expect(returned).toHaveCount(0); await expect(details.getByText('1 restored at source', { exact: true })).toBeVisible();
  await expect(details.getByRole('button', { name: 'Record returned goods', exact: true })).toHaveCount(0);
  await details.getByRole('button', { name: 'Close', exact: true }).click();
  await page.goto('/inventory'); await page.getByPlaceholder('Search by name, SKU, or barcode...').fill('Fixture Transfer');
  await expect(page.getByRole('row').filter({ hasText: 'Fixture Transfer' }).getByText('91', { exact: true })).toBeVisible();
  await logout(page); await login(page, 'receiving@example.test'); await page.goto('/inventory');
  await page.getByPlaceholder('Search by name, SKU, or barcode...').fill('Fixture Received');
  await expect(page.getByRole('row').filter({ hasText: 'Fixture Received' }).getByText('11', { exact: true })).toBeVisible();
});
