import { test, expect } from '@playwright/test';
import { login } from './utils/auth-helper';
import fs from 'fs';

test('a void with a lost response survives reload and retries without a second payout or restock', async ({ page }) => {
  await login(page, 'voids@example.test'); await page.goto('/pos');
  await page.getByRole('button', { name: /Fixture Void.*20 in stock/ }).click();
  await page.getByRole('button', { name: 'Change quantity for Fixture Void', exact: true }).click();
  const pad = page.getByRole('dialog', { name: 'Quantity for Fixture Void' });
  await pad.getByRole('button', { name: '2', exact: true }).click();
  await pad.getByRole('button', { name: 'OK', exact: true }).click();
  await page.getByRole('button', { name: 'Charge $22.00', exact: true }).click();
  await page.getByRole('button', { name: 'Skip', exact: true }).click();
  const payment = page.getByRole('dialog', { name: 'Payment', exact: true });
  await payment.getByRole('button', { name: 'Exact', exact: true }).click();
  const saved = page.waitForResponse(r => r.url().endsWith('/api/sales') && r.request().method() === 'POST');
  await payment.getByRole('button', { name: 'Charge $22.00', exact: true }).click();
  const created = await saved; expect(created.status()).toBe(201);
  const sale = (await created.json()).data;
  await page.getByRole('dialog', { name: 'Receipt', exact: true }).getByRole('button', { name: 'Done', exact: true }).click();
  await page.goto('/reports');
  const summary = page.getByText('Net collected (including tax)', { exact: true }).locator('..');
  await expect(summary).toContainText('$22.00');
  const row = page.getByRole('row').filter({ hasText: sale.saleNumber }).filter({ has: page.getByTitle('View details', { exact: true }) });
  await row.getByTitle('View details', { exact: true }).click();
  await page.getByRole('button', { name: 'Void Sale', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Void Sale', exact: true });
  await expect(dialog.getByRole('button', { name: 'Record Void', exact: true })).toBeDisabled();
  await dialog.getByLabel('Reason', { exact: true }).fill('Duplicate checkout');
  await page.screenshot({ path: 'test-results/void-confirmation-light.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await expect(dialog.getByRole('button', { name: 'Record Void', exact: true })).toBeInViewport();
  await page.screenshot({ path: 'test-results/void-confirmation-mobile-dark.png', fullPage: true, animations: 'disabled' });
  await page.route('**/api/sales/*/void', async route => {
    const committed = await route.fetch(); expect(committed.status()).toBe(200);
    await route.abort('failed');
  }, { times: 1 });
  await dialog.getByRole('button', { name: 'Record Void', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Retry the saved void');
  await page.reload(); await page.setViewportSize({ width: 1280, height: 900 });
  await expect(summary).toContainText('$0.00');
  await expect(page.getByRole('dialog', { name: 'Sale Details', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Void Details / Retry', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('Duplicate checkout');
  await page.route('**/api/sales/*/void', route => route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary access rejection during recovery' }) }), { times: 1 });
  await dialog.getByRole('button', { name: 'Retry saved void', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Temporary access rejection');
  await expect(dialog.getByRole('button', { name: 'Retry saved void', exact: true })).toBeEnabled();
  expect(await page.evaluate(() => Object.keys(localStorage).some(key => key.startsWith('pos-pending-void:')))).toBe(true);
  const retry = page.waitForResponse(r => r.url().endsWith('/void') && r.status() === 200);
  await dialog.getByRole('button', { name: 'Retry saved void', exact: true }).click();
  expect((await (await retry).json()).replayed).toBe(true);
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Voids recorded in this period', exact: true })).toBeVisible();
  const token = await page.evaluate(() => localStorage.getItem('token'));
  const headers = { Authorization: 'Bearer ' + token };
  const shift = (await (await page.request.get('/api/shifts/current', { headers })).json()).data;
  expect(shift).toMatchObject({ expectedDrawer: 100, cashVoids: 22 });
  const product = (await (await page.request.get('/api/products/' + sale.items[0].productId, { headers })).json()).data;
  expect(product.stockQuantity).toBe(20);
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('dialog', { name: 'Export Preview', exact: true }).getByRole('button', { name: 'Download CSV', exact: true }).click();
  const csv = fs.readFileSync((await (await download).path())!, 'utf8');
  expect(csv).toContain('"SALE"'); expect(csv).toContain('"VOID"'); expect(csv).toContain('"-22.00","-2.00"');
  await page.getByRole('navigation', { name: 'Insights / Reports & Analysis views' }).getByRole('link', { name: 'Overview', exact: true }).click();
  await expect(page.getByText("Today's Net Collections", { exact: true }).locator('..')).toContainText('$0.00');
  await expect(page.getByText('Voids', { exact: true }).locator('..')).toContainText('$22.00');
});
