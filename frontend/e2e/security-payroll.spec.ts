import { chooseOption, selectField } from './utils/select-helper';
import { test, expect } from '@playwright/test';
import { authenticator } from 'otplib';
import { login, logout } from './utils/auth-helper';

test('security status failure blocks controls and backup codes work at sign-in', async ({ page }) => {
  await login(page, 'two-factor@example.test');
  await page.route('**/api/auth/2fa/status', route => route.fulfill({ status: 503, json: { error: 'Unavailable' } }));
  await page.goto('/settings?section=profile');
  const card = page.getByRole('heading', { name: 'Two-Factor Authentication', exact: true }).locator('..').locator('..');
  await expect(card.getByRole('alert')).toContainText('Security changes are unavailable');
  await expect(card.getByRole('button', { name: 'Enable Two-Factor Authentication', exact: true })).toHaveCount(0);
  await page.unroute('**/api/auth/2fa/status');
  await card.getByRole('button', { name: 'Retry security status', exact: true }).click();
  await card.getByLabel('Current password', { exact: true }).fill('BrowserTest123!');
  await card.getByRole('button', { name: 'Enable Two-Factor Authentication', exact: true }).click();
  const keyText = await card.locator('span.font-mono').innerText();
  await card.getByLabel('Verification code', { exact: true }).fill(authenticator.generate(keyText.trim()));
  const enabled = page.waitForResponse(response => response.url().endsWith('/auth/2fa/verify') && response.status() === 200);
  await card.getByRole('button', { name: 'Verify & Enable', exact: true }).click();
  const codes: string[] = (await (await enabled).json()).data.backupCodes;
  expect(codes[0]).toHaveLength(16);
  await card.getByRole('button', { name: "I've saved my codes", exact: true }).click();
  await logout(page); await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('two-factor@example.test');
  await page.getByLabel('Password', { exact: true }).fill('BrowserTest123!');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await expect(page.getByLabel('Verification code', { exact: true })).toBeVisible();
  await page.getByLabel('Verification code', { exact: true }).fill(codes[0]);
  await page.getByRole('button', { name: 'Verify', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto('/settings?section=profile');
  await card.getByRole('button', { name: 'Disable', exact: true }).click();
  await card.getByLabel('Password', { exact: true }).fill('BrowserTest123!');
  await expect(card.getByRole('button', { name: 'Disable 2FA', exact: true })).toBeDisabled();
  await card.getByLabel('Authentication or backup code', { exact: true }).fill(codes[1]);
  await card.getByRole('button', { name: 'Disable 2FA', exact: true }).click();
  await expect(card.getByRole('button', { name: 'Enable Two-Factor Authentication', exact: true })).toBeVisible();
});

test('payroll reviews and cash-payment recovery survive reload and drawer closure', async ({ page }) => {
  await login(page, 'payroll@example.test'); await page.goto('/team-time/payroll');
  await page.getByRole('button', { name: 'Review payroll', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Review Payroll', exact: true });
  await expect(dialog).toContainText('$160.00');
  await dialog.getByLabel('Reason', { exact: true }).fill('Verified original payroll records');
  await dialog.getByRole('button', { name: 'Save review', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Review payroll', exact: true }).click();
  await dialog.getByLabel('Reason', { exact: true }).fill('Wages paid from owner drawer');
  await chooseOption(selectField(dialog, 'Payroll payment method'), 'Cash paid from my open drawer');
  await dialog.getByLabel('Payment reference', { exact: true }).fill('WAGE-CASH-160');
  let original: unknown;
  await page.route('**/api/payroll/expenses/*/review', async route => {
    original = route.request().postDataJSON(); const response = await route.fetch(); expect(response.status()).toBe(200); await route.abort('failed');
  }, { times: 1 });
  await dialog.getByRole('button', { name: 'Record payment', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Result uncertain');
  await page.reload();
  await expect(dialog).toBeVisible(); await expect(dialog).toContainText('PAID');
  const token = await page.evaluate(() => localStorage.getItem('token'));
  const closed = await page.request.post('/api/shifts/clock-out', { headers: { Authorization: 'Bearer ' + token }, data: { endingCash: 40 } });
  expect(closed.status()).toBe(200); expect((await closed.json()).data).toMatchObject({ expectedCash: 40, cashDifference: 0 });
  const retry = page.waitForResponse(response => response.url().includes('/payroll/expenses/') && response.url().endsWith('/review') && response.status() === 200);
  await dialog.getByRole('button', { name: 'Retry saved operation', exact: true }).click();
  const response = await retry; expect(response.request().postDataJSON()).toEqual(original); expect((await response.json()).replayed).toBe(true);
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Review payroll', exact: true }).click();
  await expect(dialog).toContainText('WAGE-CASH-160');
  await page.screenshot({ path: 'test-results/payroll-paid-light.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 }); await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.screenshot({ path: 'test-results/payroll-paid-mobile-dark.png', fullPage: true, animations: 'disabled' });
});
