import { chooseOption, selectField } from './utils/select-helper';
import { test, expect } from '@playwright/test';
import { login, TEST_USER } from './utils/auth-helper';
test('inventory search returns the matching product and stock state', async ({ page }) => {
  await login(page, TEST_USER.email); await page.goto('/inventory');
  await page.getByPlaceholder('Search by name, SKU, or barcode...').fill('Fixture Empty');
  const row = page.getByRole('row').filter({ hasText: 'Fixture Empty' });
  await expect(row).toHaveCount(1); await expect(row.getByText('Out of Stock', { exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: 'Fixture Coffee' })).toHaveCount(0);
});
for (const role of ['owner', 'manager']) test(role + ' can start a transfer to only a connected destination', async ({ page }) => {
  await login(page, role + '@example.test'); await page.goto('/inventory-transfers');
  await page.getByRole('button', { name: 'New Transfer', exact: true }).first().click();
  await expect(page.getByLabel('Source store')).toHaveValue('Store A');
  const destination = selectField(page, 'Destination store');
  await destination.locator('button').click(); await expect(page.getByRole('listbox').getByRole('option')).toHaveText(['Select...', 'Store B']); await page.keyboard.press('Escape');
  await chooseOption(destination, 'Store B');
  await page.getByRole('button', { name: '+ Add Item', exact: true }).click();
  await page.getByLabel('Search products to add').fill('Fixture Coffee');
  await page.getByRole('button', { name: /Fixture Coffee.*99 in stock/ }).click();
  const quantity = page.getByLabel('Quantity for Fixture Coffee');
  await quantity.fill('100');
  await expect(quantity).toHaveAttribute('max', '99');
  expect(await quantity.evaluate(input => (input as HTMLInputElement).validity.rangeOverflow)).toBe(true);
  await quantity.fill('3');
  const created = page.waitForResponse(r => r.url().endsWith('/api/inventory-transfers') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create Transfer', exact: true }).click();
  const response = await created; expect(response.status()).toBe(201);
  const transfer = (await response.json()).data;
  expect(transfer.status).toBe('PENDING'); expect(transfer.items[0].quantity).toBe(3);
  await expect(page.getByRole('dialog', { name: 'New Inventory Transfer' })).toHaveCount(0);
  await expect(page.getByText(transfer.transferNumber, { exact: true })).toBeVisible();
});
