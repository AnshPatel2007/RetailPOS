import { test, expect } from '@playwright/test';
import { login, logout } from './utils/auth-helper';

test('offline cash survives logout, supports store review, and replays only for its cashier', async ({ page, context }) => {
  await login(page, 'cashier@example.test');
  await page.goto('/pos');
  await page.getByRole('button', { name: /^Fixture Loyalty/ }).click();
  await page.getByRole('button', { name: 'Charge $1.10', exact: true }).click();
  const payment = page.getByRole('dialog', { name: 'Payment', exact: true });
  await payment.getByRole('button', { name: 'Exact', exact: true }).click();
  await expect(payment.getByRole('button', { name: 'Charge $1.10', exact: true })).toBeEnabled();
  await context.setOffline(true);
  await expect(payment.getByText(/Offline: cached cash total only/)).toBeVisible();
  await payment.getByRole('button', { name: 'Charge $1.10', exact: true }).click();
  await expect(payment).toHaveCount(0);
  await page.getByRole('button', { name: 'Register recovery and connection status' }).click();
  const review = page.getByRole('dialog', { name: 'Register recovery', exact: true });
  await expect(review.getByRole('heading', { name: 'Pending cash sales (1)' })).toBeVisible();
  await expect(review.getByRole('button', { name: 'Retry my cash sales' })).toBeDisabled();
  await expect(review).toContainText('Starting or reloading the POS while offline is not supported');
  await page.keyboard.press('Escape');
  let originalPayload: unknown;
  await page.route('**/api/sales', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    originalPayload = route.request().postDataJSON();
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Recovery fixture unavailable' }) });
  });
  await context.setOffline(false);
  await expect.poll(() => originalPayload).toBeTruthy();
  await logout(page);
  await login(page, 'manager@example.test');
  await page.goto('/pos');
  const status = page.getByRole('button', { name: 'Register recovery and connection status' });
  await expect(status).not.toContainText('1 pending');
  await status.click();
  await expect(review.getByRole('heading', { name: 'Pending cash sales (1)' })).toBeVisible();
  await expect(review).toContainText('Another cashier’s checkout');
  await expect(review).toContainText('Recovery fixture unavailable');
  await expect(review.getByRole('button', { name: 'Retry my cash sales' })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await logout(page);
  await login(page, 'voids@example.test');
  await page.goto('/pos'); await status.click();
  await expect(review.getByRole('heading', { name: 'Pending cash sales (0)' })).toBeVisible();
  await expect(review).not.toContainText('Recovery fixture unavailable');
  await page.keyboard.press('Escape');
  await logout(page);
  await login(page, 'cashier@example.test');
  await page.goto('/pos'); await status.click();
  await expect(review.getByRole('heading', { name: 'Pending cash sales (1)' })).toBeVisible();
  await page.unroute('**/api/sales');
  const saved = page.waitForResponse(response => response.url().endsWith('/api/sales') && response.request().method() === 'POST');
  await review.getByRole('button', { name: 'Retry my cash sales' }).click();
  const response = await saved;
  expect(response.status()).toBe(201);
  expect(response.request().postDataJSON()).toEqual(originalPayload);
  await expect(review.getByRole('heading', { name: 'Pending cash sales (0)' })).toBeVisible();
  await expect(review.getByText(/Product cache:/)).not.toContainText('Not available');
});
